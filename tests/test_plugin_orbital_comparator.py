class _FakeMesh:
    def __init__(self, n_points=10):
        self.n_points = n_points


class _FakeGrid:
    """Stands in for the pyvista StructuredGrid a cube parses into."""

    def __init__(self):
        self.contour_levels = []

    def contour(self, levels, scalars=None):
        self.contour_levels.append(levels[0])
        return _FakeMesh()


@pytest.fixture
def comparator(tmp_path):
    """A live OrbitalComparator with a mocked plotter."""
    from orbital_comparator_harness import load_with_stateful_qt

