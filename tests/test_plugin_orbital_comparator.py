class TestRunEntryPoint:
    def _module(self):
        from orbital_comparator_harness import load_with_stateful_qt

        return load_with_stateful_qt(ORBITAL_COMPARATOR_PATH)

    def _ready_module(self, mw):
        mod = self._module()
        ctx = MagicMock()
        ctx.get_main_window.return_value = mw
        mod.initialize(ctx)
        return mod

    def test_the_first_run_builds_and_stores_the_window(self):
        mw = SimpleNamespace(plotter=MagicMock())
        mod = self._ready_module(mw)
        mod.run(mw)
        assert isinstance(mw.orbital_comparator_window, mod.OrbitalComparator)

    def test_the_window_is_shown(self):
        mw = SimpleNamespace(plotter=MagicMock())
        mod = self._ready_module(mw)
        mod.run(mw)
        assert mw.orbital_comparator_window.isVisible()

    def test_running_again_toggles_it_closed(self):
        mw = SimpleNamespace(plotter=MagicMock())
        mod = self._ready_module(mw)
        mod.run(mw)
        first = mw.orbital_comparator_window
        mod.run(mw)
        assert mw.orbital_comparator_window is first
        assert not first.isVisible()

    def test_it_reuses_the_existing_window(self):
        mw = SimpleNamespace(plotter=MagicMock())
        mod = self._ready_module(mw)
        mod.run(mw)
        first = mw.orbital_comparator_window
        mod.run(mw)  # closes
        mod.run(mw)  # reopens the same instance
        assert mw.orbital_comparator_window is first
        assert first.isVisible()

    def test_a_wrapped_main_window_is_unwrapped(self):
        """The host passes a wrapper carrying the real window as .host."""
        real = SimpleNamespace(plotter=MagicMock())
        mod = self._ready_module(real)
        mod.run(SimpleNamespace(host=real))
        assert hasattr(real, "orbital_comparator_window")

    def test_running_without_initialize_does_nothing(self):
        mw = SimpleNamespace(plotter=MagicMock())
        mod = self._module()  # PLUGIN_CONTEXT still None
        mod.run(mw)
        assert not hasattr(mw, "orbital_comparator_window")


