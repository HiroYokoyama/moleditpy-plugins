class TestParseCube:
    def _parse(self):
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            return mod.parse_cube

    def test_reads_dimensions_and_origin(self, tmp_path):
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            meta = mod.parse_cube(str(_write_cube(tmp_path, dims=(2, 3, 4))))
        assert meta["dims"] == (2, 3, 4)
        assert list(meta["origin"]) == [0.0, 0.0, 0.0]

    def test_reads_every_data_point(self, tmp_path):
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            meta = mod.parse_cube(str(_write_cube(tmp_path, dims=(2, 3, 4))))
        assert len(meta["data"]) == 2 * 3 * 4

    def test_skips_the_atom_records(self, tmp_path):
        """Atom lines sit between the axes and the data; miscounting them
        shifts every value."""
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            meta = mod.parse_cube(str(_write_cube(tmp_path, n_atoms=3)))
        assert meta["data"][0] == 0.0
        assert meta["data"][-1] == 7.0

    def test_a_negative_atom_count_skips_the_dset_block(self, tmp_path):
        """An MO cube carries a DSET_IDS record the data does not include."""
        path = tmp_path / "mo.cube"
        path.write_text(
            "comment\nstamp\n-1 0.0 0.0 0.0\n"
            "2 0.5 0.0 0.0\n2 0.0 0.5 0.0\n2 0.0 0.0 0.5\n"
            "8 8.0 0.0 0.0 0.0\n"
            "1 7\n"
            + " ".join(str(float(v)) for v in range(8))
            + "\n",
            encoding="utf-8",
        )
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            meta = mod.parse_cube(str(path))
        assert len(meta["data"]) == 8
        assert meta["data"][0] == 0.0

    def test_interleaved_datasets_take_the_first_orbital(self, tmp_path):
        """Two orbitals in one cube interleave point by point; reshaping the
        whole stream would raise, and taking a contiguous half would mix
        them."""
        path = tmp_path / "two.cube"
        values = []
        for i in range(8):
            values += [float(i), 900.0 + i]  # orbital 0, orbital 1
        path.write_text(
            "comment\nstamp\n-1 0.0 0.0 0.0\n"
            "2 0.5 0.0 0.0\n2 0.0 0.5 0.0\n2 0.0 0.0 0.5\n"
            "8 8.0 0.0 0.0 0.0\n"
            "2 7 8\n" + " ".join(str(v) for v in values) + "\n",
            encoding="utf-8",
        )
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            meta = mod.parse_cube(str(path))
        assert len(meta["data"]) == 8
        assert list(meta["data"]) == [float(i) for i in range(8)]

    def test_a_negative_voxel_count_flags_angstrom(self, tmp_path):
        """Gaussian marks Angstrom grids with a negative NX; treating those as
        Bohr inflates the isosurface by 1.89x."""
        path = tmp_path / "ang.cube"
        path.write_text(
            "comment\nstamp\n1 0.0 0.0 0.0\n"
            "-2 0.5 0.0 0.0\n2 0.0 0.5 0.0\n2 0.0 0.0 0.5\n"
            "8 8.0 0.0 0.0 0.0\n"
            + " ".join(str(float(v)) for v in range(8))
            + "\n",
            encoding="utf-8",
        )
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            meta = mod.parse_cube(str(path))
        assert meta["is_angstrom"] is True
        assert meta["dims"] == (2, 2, 2)

    def test_a_blank_line_in_the_dset_block_does_not_hang(self, tmp_path):
        """A line consuming no ids used to spin the loop forever, freezing the
        whole app on a malformed file."""
        path = tmp_path / "blank.cube"
        path.write_text(
            "comment\nstamp\n-1 0.0 0.0 0.0\n"
            "2 0.5 0.0 0.0\n2 0.0 0.5 0.0\n2 0.0 0.0 0.5\n"
            "8 8.0 0.0 0.0 0.0\n"
            "3\n"
            "\n"
            "7 8 9\n" + " ".join(str(float(v)) for v in range(24)) + "\n",
            encoding="utf-8",
        )
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            meta = mod.parse_cube(str(path))
        assert len(meta["data"]) == 8

    def test_a_cube_ending_inside_its_dset_block_raises(self, tmp_path):
        path = tmp_path / "cut.cube"
        path.write_text(
            "comment\nstamp\n-1 0.0 0.0 0.0\n"
            "2 0.5 0.0 0.0\n2 0.0 0.5 0.0\n2 0.0 0.0 0.5\n"
            "8 8.0 0.0 0.0 0.0\n"
            "5\n",
            encoding="utf-8",
        )
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            with pytest.raises(ValueError):
                mod.parse_cube(str(path))

    def test_a_truncated_cube_raises_rather_than_returning_junk(self, tmp_path):
        path = tmp_path / "bad.cube"
        path.write_text("comment\nstamp\n", encoding="utf-8")
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)
            with pytest.raises((IndexError, ValueError)):
                mod.parse_cube(str(path))


class TestBuildGrid:
    def _grid_points(self, meta_overrides=None):
        """build_grid against a fake pyvista StructuredGrid that keeps state."""
        with mocks_with_real_numpy():
            mod = load_plugin(ORBITAL_COMPARATOR_PATH)

            class _Grid:
                def __init__(self):
                    self.points = None
                    self.dimensions = None
                    self.point_data = {}

            mod.pv = SimpleNamespace(StructuredGrid=_Grid)
            meta = {
                "dims": (2, 2, 2),
                "origin": mod.np.array([0.0, 0.0, 0.0]),
                "vectors": (
                    mod.np.array([1.0, 0.0, 0.0]),
                    mod.np.array([0.0, 1.0, 0.0]),
                    mod.np.array([0.0, 0.0, 1.0]),
                ),
                "data": mod.np.arange(8, dtype=float),
                "is_angstrom": False,
            }
            meta.update(meta_overrides or {})
            return mod, mod.build_grid(meta)

    def test_bohr_grids_are_converted_to_angstrom(self):
        mod, grid = self._grid_points()
        # One Bohr step along x becomes 0.529 A.
        xs = sorted({p[0] for p in grid.points})
        assert xs[1] == pytest.approx(0.529177249)

    def test_angstrom_grids_are_left_alone(self):
        mod, grid = self._grid_points({"is_angstrom": True})
        xs = sorted({p[0] for p in grid.points})
        assert xs[1] == pytest.approx(1.0)

    def test_dimensions_are_passed_through(self):
        _mod, grid = self._grid_points()
        assert list(grid.dimensions) == [2, 2, 2]

    def test_values_are_reordered_for_the_point_layout(self):
        """Cube data is Z-fastest, grid points are X-fastest; skipping the
        reorder silently mirrors the orbital."""
        _mod, grid = self._grid_points()
        assert list(grid.point_data["values"]) == [0, 4, 2, 6, 1, 5, 3, 7]


