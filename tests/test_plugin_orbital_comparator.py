def _write_cube(tmp_path, name="mo.cube", stamp=None, dims=(2, 2, 2), n_atoms=1):
    """A minimal but well-formed cube file."""
    nx, ny, nz = dims
    header = stamp if stamp is not None else "Generated by ORCA Result Analyzer v3.13.2 | grid=40 | margin=4.00"
    lines = [
        "ORCA Analyzer Cube File: MO 5",
        header,
        f"{n_atoms} 0.000000 0.000000 0.000000",
        f"{nx} 0.500000 0.000000 0.000000",
        f"{ny} 0.000000 0.500000 0.000000",
        f"{nz} 0.000000 0.000000 0.500000",
    ]
    for _ in range(n_atoms):
        lines.append("8 8.000000 0.000000 0.000000 0.000000")
    values = [f"{v:.5E}" for v in range(nx * ny * nz)]
    lines.append(" ".join(values))
    path = tmp_path / name
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


