def _fill(env, index, iso=0.02):
    """Put a loaded cube into a slot without touching the filesystem."""
    slot = env.win.slots[index]
    slot.grid = _FakeGrid()
    slot.path = f"/cubes/mo{index}.cube"
    slot.settings = {"grid": 40, "margin": 4.0, "version": "3.13.2"}
    slot.check_on.setChecked(True)
    slot.spin_iso.setValue(iso)
    return slot


def _meshes(env):
    """Actor names the plotter was asked to draw."""
    return [
        c.kwargs["name"]
        for c in env.mw.plotter.add_mesh.call_args_list
        if "name" in c.kwargs
    ]


